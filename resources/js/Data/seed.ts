const AGORA = new Date();

function dois(n: number): string {
    return String(n).padStart(2, '0');
}

/** `hoje - 3 dias`, em ISO curto, escrito em hora local. */
function dia(desvio = 0): string {
    const d = new Date(AGORA);

    d.setDate(d.getDate() + desvio);

    return `${d.getFullYear()}-${dois(d.getMonth() + 1)}-${dois(d.getDate())}`;
}

/** `hoje - 2 dias, 09:30`, em ISO local. */
function momento(desvioDias: number, hora: number, minuto = 0): string {
    const d = new Date(AGORA);

    d.setDate(d.getDate() + desvioDias);
    d.setHours(hora, minuto, 0, 0);

    return `${dia(desvioDias)}T${dois(d.getHours())}:${dois(d.getMinutes())}:00`;
}

